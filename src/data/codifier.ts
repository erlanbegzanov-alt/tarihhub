/**
 * The НЦТ codifier for «История Казахстана» — 7 sections, 55 topics.
 *
 * Without this table a `topicId` is a bare number and a result screen can only
 * say "you scored 14/20". With it, the same screen can name the topic the
 * marks were lost on, which is the entire point of tagging the bank.
 *
 * Provenance, kept honest:
 * - Section numbers, their Russian AND Kazakh names, and the topic ranges are
 *   official — `history-reference/ent-exam-patterns.md` §6.1, from the 2026
 *   specification.
 * - Russian topic titles are condensed from the official list in §6.2, which
 *   is itself marked there as abridged. They are shortened to fit a UI row;
 *   for the full wording go to the specification, not to this file.
 * - Kazakh topic titles are TRANSLATIONS made here, not quotations from the
 *   Kazakh specification. The Kazakh section names are official; the Kazakh
 *   topic names are not, and must never be presented as the ministry's wording.
 *
 * Topics 53–55 are the context-task topics. They never sit on a standalone
 * question — only on a `ContextBlock`.
 */

export interface CodifierSection {
  /** 1–7, matching the specification's own numbering. */
  id: number
  name: LocalizedText
  /** Inclusive range of topic ids this section owns. */
  from: TopicId
  to: TopicId
}

export interface CodifierTopic {
  id: TopicId
  section: number
  title: LocalizedText
}

