const BY_ID = new Map(codifierTopics.map((t) => [t.id, t]))

/** The topic, or `undefined` for a number outside 1–55. */
export function codifierTopic(id: TopicId | undefined): CodifierTopic | undefined {
  return id === undefined ? undefined : BY_ID.get(id)
}

/** "24 · Реформы 1822–1824 годов…" — the label a result row shows. */
export function topicLabel(id: TopicId | undefined, lang: 'kz' | 'ru'): string {
  const topic = codifierTopic(id)
  return topic ? `${topic.id} · ${topic.title[lang]}` : String(id ?? '')
}

